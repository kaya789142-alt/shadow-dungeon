import assert from 'node:assert/strict'
import { chromium, devices } from 'playwright'

const base=process.env.SHADOW_TEST_URL??'http://localhost:5173/'
const key='shadow-dungeon.v1'
const browser=await chromium.launch({executablePath:process.env.SHADOW_CHROMIUM})
const {defaultBrowserType,...tablet}=devices['iPad Pro 11 landscape']
try{
 const page=await browser.newPage(tablet)
 const errors=[],art=[]
 page.on('pageerror',error=>errors.push(error.message))
 page.on('response',response=>{if(response.ok()&&response.url().endsWith('/art-v30/items.webp'))art.push(response.url())})
 const button=(name)=>page.getByRole('button',{name,exact:true})
 const read=()=>page.evaluate(key=>JSON.parse(localStorage.getItem(key)),key)
 const travelState=zone=>page.waitForFunction(([key,zone])=>JSON.parse(localStorage.getItem(key))?.zone===zone,[key,zone])
 await page.goto(base)
 await button('開始冒險').click()
 await page.getByLabel('角色名稱').fill('遠行旅人')
 await button('進入燼燈村').click()

 await button('背包').tap()
 await page.getByRole('heading',{name:'冒險背包'}).waitFor()
 await button('消耗品').tap()
 assert.equal(await page.locator('[data-action^="equip:"]').count(),0)
 await button('武器').tap()
 await page.locator('[data-action^="compare:"]').first().tap()
 await page.getByRole('heading',{name:'比較主武器'}).waitFor()
 await button('自動排序').tap()
 await button('收合視窗').tap()
 assert.equal(await page.locator('.panel-body').count(),0)
 await button('展開視窗').tap()
 await button('縮小視窗').tap()
 assert.equal(await page.locator('.panel-body').count(),0)
 await button('還原視窗').tap()
 await button('關閉視窗').tap()
 await button('收合小地圖').tap()
 assert.equal(await button('開啟區域地圖').isVisible(),false)
 await button('展開小地圖').tap()
 await button('收合任務追蹤').tap()
 assert.equal(await page.locator('#tracker').isVisible(),false)
 await button('展開任務追蹤').tap()
 await button('暗影地下城首頁').tap()
 await page.evaluate(key=>{
  const data=JSON.parse(localStorage.getItem(key))
  data.x=1470;data.y=535
  delete data.coordinates;delete data.drops;delete data.pickup;delete data.locks
  localStorage.setItem(key,JSON.stringify(data))
 },key)
 await page.reload()
 await button('繼續冒險').tap()
 const start=await read()
 assert.equal(start.coordinates,'region-local')
 assert.equal(start.x,1470)
 assert.equal(start.pickup.enabled,true)
 await page.evaluate(()=>window.originalCanvas=document.querySelector('#game canvas'))
 await page.keyboard.down('d')
 await travelState(1)
 await page.keyboard.up('d')
 const forest=await read()
 assert.ok(forest.x<120)
 assert.equal(forest.y,535)
 assert.equal('shift' in forest,false)
 await page.keyboard.down('a')
 await travelState(0)
 await page.keyboard.up('a')
 assert.ok((await read()).x>1400)
 assert.ok(await page.evaluate(()=>window.originalCanvas===document.querySelector('#game canvas')))
 assert.ok(Number(await page.locator('#game').getAttribute('data-maps'))<=2)
 assert.ok(art.length,'inventory images must load from the project base')
 console.log('視窗收合、裝備比較、分類、重載 V2.2 座標及雙向跨區步行通過')

 await button('暗影地下城首頁').tap()
 await page.evaluate(key=>{
  const data=JSON.parse(localStorage.getItem(key)), weapon=data.bag.find(item=>item.slot===0)
  data.zone=0;data.x=805;data.y=552
  data.bag=[weapon,...Array.from({length:59},(_,i)=>({...data.bag.find(g=>g.slot===3),uid:'qa-armor-'+i}))]
  data.locks=[weapon.uid,'red']
  data.drops={0:[{x:811,y:559,gold:28,material:'red',gear:{...data.bag[1],uid:'qa-ground-gear',grade:3}}]}
  localStorage.setItem(key,JSON.stringify(data))
 },key)
 await page.reload()
 await button('繼續冒險').tap()
 await page.waitForFunction(([key,gold])=>JSON.parse(localStorage.getItem(key)).gold===gold,[key,start.gold+28])
 let save=await read()
 assert.equal(save.drops[0][0].gear.uid,'qa-ground-gear')
 assert.equal(save.items.red,start.items.red+1)
 assert.equal(save.bag.length,60)
 await button('拾取戰利品').tap()
 assert.equal((await read()).gold,start.gold+28)
 await button('設定').tap()
 await page.getByLabel('自動拾取有效範圍內的戰利品').uncheck()
 await button('關閉視窗').tap()
 await button('商店').tap()
 await button('出售分頁').tap()
 const weaponRow=page.locator('.item-row').filter({hasText:/旅人・闊劍/}).last()
 assert.match(await weaponRow.textContent(),/已鎖定/)
 assert.equal(await page.locator('[data-action="sell-material:red"]').count(),0)
 await page.locator('[data-action="sell:qa-armor-0"]').tap()
 await button('確認出售').tap()
 const expected=(await read()).gold
 await button('關閉視窗').tap()
 assert.equal((await read()).bag.length,59)
 await button('拾取戰利品').tap()
 save=await read()
 assert.equal(save.bag.length,60)
 assert.equal(save.bag.filter(item=>item.uid==='qa-ground-gear').length,1)
 assert.deepEqual(save.drops[0],[])
 assert.equal(save.gold,expected)
 assert.deepEqual(errors,[])
 console.log('自動拾取、滿包留地面、鎖定出售、手動拾取與防重複通過')
}finally{await browser.close()}
